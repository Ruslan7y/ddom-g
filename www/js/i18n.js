export function detectLang() {
  const n = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return S[n] ? n : 'en';
}
export function t(key, vars) {
  let s = (S[lang] && S[lang][key]) ?? S.en[key] ?? key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
